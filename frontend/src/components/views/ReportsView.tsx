import React, { useState, useEffect } from 'react';
import {
  FileSpreadsheet,
  Download,
  ShieldCheck,
  Check,
  FileJson,
  FileText,
  AlertCircle,
} from 'lucide-react';
import { useAuth } from '../../context/AuthContext';
import { getNodes, getDecisions, verifyAuditChain, buildSanitizedReportData } from '../../services/api';
import { NodeItem, Decision } from '../../types/api';

export const ReportsView: React.FC = () => {
  const { isDemoMode, currentUser } = useAuth();
  const [format, setFormat] = useState<'json' | 'csv'>('json');
  const [nodes, setNodes] = useState<NodeItem[]>([]);
  const [decisions, setDecisions] = useState<Decision[]>([]);
  const [auditValid, setAuditValid] = useState<boolean>(true);
  const [isLoading, setIsLoading] = useState<boolean>(true);
  const [downloadSuccess, setDownloadSuccess] = useState<boolean>(false);

  useEffect(() => {
    let mounted = true;
    setIsLoading(true);

    Promise.allSettled([
      getNodes({}, isDemoMode),
      getDecisions({}, isDemoMode),
      verifyAuditChain(isDemoMode),
    ]).then(([nodesRes, decisionsRes, auditRes]) => {
      if (!mounted) return;
      if (nodesRes.status === 'fulfilled') setNodes(nodesRes.value.results || []);
      if (decisionsRes.status === 'fulfilled') setDecisions(decisionsRes.value.results || []);
      if (auditRes.status === 'fulfilled') setAuditValid(auditRes.value.valid);
      setIsLoading(false);
    });

    return () => {
      mounted = false;
    };
  }, [isDemoMode]);

  const reportData = buildSanitizedReportData(
    currentUser?.username || 'anonymous',
    nodes,
    decisions,
    auditValid
  );

  const convertToCSV = (data: typeof reportData): string => {
    const lines: string[] = [];
    lines.push('--- FOGTRUST SANITIZED AUDIT REPORT ---');
    lines.push(`Generated At,${data.generated_at}`);
    lines.push(`Generated By,${data.generated_by}`);
    lines.push(`Total Nodes,${data.summary.total_nodes}`);
    lines.push(`Active Nodes,${data.summary.active_nodes}`);
    lines.push(`Revoked Nodes,${data.summary.revoked_nodes}`);
    lines.push(`Average Trust Score,${data.summary.average_trust_score}`);
    lines.push(`Audit Chain Verified,${data.summary.audit_chain_verified}`);
    lines.push('');
    lines.push('--- NODES (SANITIZED) ---');
    lines.push('ID,Name,Status,Trust Score,Capacity,Current Load,Last Seen');
    data.nodes.forEach((n) => {
      lines.push(
        `"${n.id}","${n.name}","${n.status}",${n.trust_score},${n.capacity},${n.current_load},"${n.last_seen_at || 'Never'}"`
      );
    });
    lines.push('');
    lines.push('--- RECENT DECISIONS (SANITIZED) ---');
    lines.push('Decision ID,Subject Type,Decision,Reason Code,Explanation,Latency ms,Decided At');
    data.recent_decisions.forEach((d) => {
      lines.push(
        `"${d.decision_id}","${d.subject_type}","${d.decision}","${d.reason_code}","${d.explanation.replace(/"/g, '""')}",${d.latency_ms},"${d.decided_at}"`
      );
    });
    return lines.join('\n');
  };

  const handleDownload = () => {
    let content = '';
    let mimeType = '';
    let extension = '';

    if (format === 'json') {
      content = JSON.stringify(reportData, null, 2);
      mimeType = 'application/json';
      extension = 'json';
    } else {
      content = convertToCSV(reportData);
      mimeType = 'text/csv';
      extension = 'csv';
    }

    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `fogtrust-sanitized-report-${new Date().toISOString().split('T')[0]}.${extension}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    setDownloadSuccess(true);
    setTimeout(() => setDownloadSuccess(false), 3000);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl font-bold text-slate-100 flex items-center gap-2">
            <FileSpreadsheet className="w-5 h-5 text-teal-400" />
            Sanitized Report Generator (FR-7 / M4)
          </h1>
          <p className="text-sm text-slate-400 mt-0.5">
            Export compliance-ready summaries for auditors and stakeholders. Strictly strips all cryptographic secrets.
          </p>
        </div>

        <button
          onClick={handleDownload}
          disabled={isLoading}
          className="flex items-center gap-2 px-4 py-2 rounded-lg bg-teal-600 hover:bg-teal-500 text-white text-xs font-medium transition-colors shadow-sm disabled:opacity-50"
        >
          {downloadSuccess ? (
            <>
              <Check className="w-4 h-4 text-white" />
              <span>Downloaded Successfully</span>
            </>
          ) : (
            <>
              <Download className="w-4 h-4" />
              <span>Export {format.toUpperCase()} Report</span>
            </>
          )}
        </button>
      </div>

      {/* Security Assurance Banner */}
      <div className="p-4 rounded-xl bg-teal-950/30 border border-teal-800/60 text-xs text-teal-200">
        <div className="flex items-center gap-2 font-bold text-sm text-teal-300 mb-1">
          <ShieldCheck className="w-4 h-4 text-teal-400" />
          <span>Strict Redaction Guarantees (API Contract 5.10)</span>
        </div>
        <p className="text-teal-300/80 mb-3">
          This export routine guarantees that the resulting document never contains:
        </p>
        <div className="grid grid-cols-2 sm:grid-cols-5 gap-2 font-mono text-[11px]">
          <div className="flex items-center gap-1.5 p-2 bg-slate-950/60 rounded border border-teal-900/40">
            <Check className="w-3.5 h-3.5 text-teal-400" />
            <span>No Public Keys</span>
          </div>
          <div className="flex items-center gap-1.5 p-2 bg-slate-950/60 rounded border border-teal-900/40">
            <Check className="w-3.5 h-3.5 text-teal-400" />
            <span>No Token Hashes</span>
          </div>
          <div className="flex items-center gap-1.5 p-2 bg-slate-950/60 rounded border border-teal-900/40">
            <Check className="w-3.5 h-3.5 text-teal-400" />
            <span>No Ciphertexts</span>
          </div>
          <div className="flex items-center gap-1.5 p-2 bg-slate-950/60 rounded border border-teal-900/40">
            <Check className="w-3.5 h-3.5 text-teal-400" />
            <span>No Passwords</span>
          </div>
          <div className="flex items-center gap-1.5 p-2 bg-slate-950/60 rounded border border-teal-900/40">
            <Check className="w-3.5 h-3.5 text-teal-400" />
            <span>No Source IPs</span>
          </div>
        </div>
      </div>

      {/* Format Selector */}
      <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 flex items-center justify-between">
        <span className="text-xs font-medium text-slate-300 font-mono">Select Export Format:</span>
        <div className="flex items-center gap-2">
          <button
            onClick={() => setFormat('json')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg border text-xs font-mono transition-colors ${
              format === 'json'
                ? 'bg-teal-600 text-white border-teal-500 font-bold'
                : 'bg-slate-950 border-slate-800 text-slate-400 hover:text-slate-200'
            }`}
          >
            <FileJson className="w-3.5 h-3.5" />
            <span>JSON Document</span>
          </button>
          <button
            onClick={() => setFormat('csv')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg border text-xs font-mono transition-colors ${
              format === 'csv'
                ? 'bg-teal-600 text-white border-teal-500 font-bold'
                : 'bg-slate-950 border-slate-800 text-slate-400 hover:text-slate-200'
            }`}
          >
            <FileText className="w-3.5 h-3.5" />
            <span>CSV Spreadsheet</span>
          </button>
        </div>
      </div>

      {/* Live Preview Box */}
      <div className="p-5 rounded-xl bg-slate-900/60 border border-slate-800 space-y-3">
        <div className="flex items-center justify-between">
          <span className="text-xs font-mono uppercase text-slate-400">
            Live Sanitized Data Preview ({format.toUpperCase()})
          </span>
          <span className="text-[11px] text-slate-500 font-mono">
            Generated: {new Date(reportData.generated_at).toLocaleTimeString()}
          </span>
        </div>

        <div className="p-4 bg-slate-950 border border-slate-800 rounded-lg overflow-x-auto max-h-[420px]">
          <pre className="font-mono text-[11px] text-slate-300 whitespace-pre-wrap select-all">
            {format === 'json'
              ? JSON.stringify(reportData, null, 2)
              : convertToCSV(reportData)}
          </pre>
        </div>
      </div>
    </div>
  );
};

